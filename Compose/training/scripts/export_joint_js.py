#!/usr/bin/env python3
"""Export a StructuredJoint checkpoint for the browser (vendor/lib/joint-weights.js)
and write a PyTorch parity fixture for the JavaScript decoder test.

The weights are stored once, as little-endian float32 in one base64 string, with a
manifest of tensor names, offsets and shapes. No quantisation: the browser decoder
computes the same function as the evaluated checkpoint.

  python training/scripts/export_joint_js.py training/runs/joint-v1/structured/model.pt \
      vendor/lib/joint-weights.js tests/fixtures/joint-parity.json
"""
import argparse, base64, hashlib, json, time
from pathlib import Path
import numpy as np
import torch
from joint_data import (load_corpus, build_windows, collate, STREAMS, VOCAB, T_MAX, N_PITCHES, N_METER, N_POS, N_LEVEL,
                        N_PHRASE, N_LKEY, N_STYLE, N_SINCE, N_QUAL, STYLE_IDS, BEAT_OF_METER)
from evaluate_joint import load_joint

ROOT = Path(__file__).resolve().parents[1]


def export_weights(model, ckpt_path, out_path, candidate=False):
    sd = model.state_dict()
    parts, manifest, offset = [], [], 0
    for name, tensor in sd.items():
        a = tensor.detach().cpu().float().numpy().astype('<f4').ravel()
        manifest.append([name, offset, list(tensor.shape)])
        parts.append(a); offset += a.size
    blob = np.concatenate(parts).astype('<f4').tobytes()
    if candidate:
        ckpt = torch.load(ckpt_path, map_location='cpu', weights_only=False)
        if not ckpt.get('sourceHash') or not isinstance(ckpt.get('step'), int):
            raise ValueError('candidate export requires a selected fine-tuned base checkpoint')
        selected_step = ckpt['step']
        training_note = ('Four-track backbone fine-tuned from the backed-up joint-v1 model during the '
                         'expression run on OpenScore Lieder (CC0 1.0). The expression sidecar and the '
                         'separately trained arrangement adapter are not included in this browser export.')
    else:
        training = json.loads((Path(ckpt_path).parent / 'training.json').read_text())
        selected_step = training.get('selectedStep')
        training_note = ('Synthetic pretraining (phrases from the project rule system) then fine-tuning on OpenScore '
                         'Lieder (CC0 1.0) with its bundled automatic AugmentedNet analyses; model selected on the '
                         'Lieder validation split. See training/JOINT-MODEL-DESIGN.md.')
    meta = {
        'name': 'AIlegro joint R/H/B/M Transformer (StructuredJoint)',
        'config': model.config,
        'parameters': int(sum(p.numel() for p in model.parameters())),
        'streams': STREAMS, 'vocab': VOCAB, 'contextSteps': T_MAX, 'pitches': N_PITCHES,
        'controls': {'meter': N_METER, 'pos': N_POS, 'level': N_LEVEL, 'phrase': N_PHRASE, 'lkey': N_LKEY,
                     'style': N_STYLE, 'since': N_SINCE, 'qualities': N_QUAL},
        'styleIds': STYLE_IDS, 'beatOfMeter': BEAT_OF_METER,
        'checkpoint': {'path': str(Path(ckpt_path)),
                       'sha256': hashlib.sha256(Path(ckpt_path).read_bytes()).hexdigest(),
                       'selectedStep': selected_step,
                       'steps': (None if candidate else sum(int((training.get('args') or {}).get(k, 0))
                                                         for k in ('pretrain_steps', 'finetune_steps')) or None),
                       'final': None if candidate else training.get('final')},
        'training': training_note,
        'exported': time.strftime('%Y-%m-%d'),
        'float32Count': offset,
    }
    b64 = base64.b64encode(blob).decode()
    js = ('// Generated by training/scripts/export_joint_js.py - do not edit by hand.\n'
          '// AIlegro joint R/H/B/M Transformer weights: little-endian float32, one base64 blob.\n'
          '// Provenance and licence notes: vendor/JOINT-MODEL-NOTICE.txt.\n'
          f'export const JOINT_META = {json.dumps(meta, ensure_ascii=False)};\n'
          f'export const JOINT_MANIFEST = {json.dumps(manifest, separators=(",", ":"))};\n'
          f'export const JOINT_WEIGHTS_BASE64 = "{b64}";\n')
    Path(out_path).write_text(js)
    return meta, len(js)


def parity_fixture(model, out_path, n_windows=2):
    """Real validation windows: inputs plus reference logits at chosen positions."""
    rows = build_windows(load_corpus(ROOT / 'data/joint/lieder-joint.npz'), 'validation')
    syn = build_windows(load_corpus(ROOT / 'data/joint/synthetic-joint.npz'), 'validation')
    rng = np.random.default_rng(7)
    picks = [rows[i] for i in rng.choice(len(rows), n_windows, replace=False)]
    picks.append(next(w for w in syn if w['style'] == 1 and int(w['meter'][0]) == 1 and w['info']['melodyBase'] is not None))
    cases = []
    for w in picks:
        n = int(w['valid'].sum())
        with torch.no_grad():
            lg = model(collate([w]))
        positions = sorted(set([0, 1, 5, n // 3, n // 2, n - 2]))
        keys = ('R', 'H', 'B', 'M', 'pos', 'meter', 'level', 'phrase', 'lkey', 'beatphase', 'barlen', 'beatlen')
        cases.append({
            'source': w['info']['scoreId'], 'steps': n,
            'globals': {'domain': int(w['domain']), 'style': int(w['style']), 'refmode': int(w['refmode'])},
            'inputs': {k: w[k][:n].astype(int).tolist() for k in keys},
            'expected': {str(t): {s: [round(float(x), 5) for x in lg[s][0, t]] for s in STREAMS} for t in positions},
        })
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(json.dumps({'note': 'Reference logits from PyTorch StructuredJoint.forward (float32). '
                                          'Position t predicts step t+1 of each stream.', 'cases': cases}))
    return [c['source'] for c in cases]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('checkpoint', type=Path); ap.add_argument('weights_js', type=Path); ap.add_argument('fixture', type=Path)
    ap.add_argument('--candidate', action='store_true', help='export the continued-training backbone as an optional A/B candidate')
    a = ap.parse_args(); torch.set_num_threads(2)
    model, kind = load_joint(a.checkpoint)
    assert kind == 'structured', kind
    model.eval()
    meta, size = export_weights(model, a.checkpoint, a.weights_js, candidate=a.candidate)
    sources = parity_fixture(model, a.fixture)
    print(json.dumps({'parameters': meta['parameters'], 'floats': meta['float32Count'], 'jsBytes': size,
                      'sha256': meta['checkpoint']['sha256'][:16], 'fixture': sources}))


if __name__ == '__main__':
    main()
