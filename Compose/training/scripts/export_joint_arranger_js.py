#!/usr/bin/env python3
"""Export the selected six-group note classifier and a browser parity probe."""
import base64
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
from train_joint_arrangement import ArrangementAdapter, PITCH_CLS

ROOT = Path(__file__).resolve().parents[2]
CHECKPOINT = ROOT / 'training/runs/joint-continued-arrangement-v1/best.pt'
OUTPUT = ROOT / 'frontend/vendor/lib/joint-arranger-weights.js'
FIXTURE = ROOT / 'tests/fixtures/joint-arranger-parity.json'


def main():
    checkpoint = torch.load(CHECKPOINT, map_location='cpu', weights_only=False)
    model = ArrangementAdapter()
    model.load_state_dict(checkpoint['model'])
    model.eval()
    parts, manifest, offset = [], [], 0
    for name, tensor in checkpoint['model'].items():
        # The three reconstruction heads are train-only, never used to infer a
        # group for an observed note. Do not ship unused weights to the browser.
        if name.startswith(('pitch_head.', 'pos_head.', 'dur_head.')):
            continue
        array = tensor.detach().cpu().numpy().astype('<f4').ravel()
        manifest.append([name, offset, list(tensor.shape)])
        parts.append(array)
        offset += array.size
    meta = {'checkpointSha256': hashlib.sha256(CHECKPOINT.read_bytes()).hexdigest(),
            'selectedStep': checkpoint['step'], 'float32Count': offset,
            'gridPerQuarter': 12, 'pitchCls': PITCH_CLS,
            'groupIds': ['woodwinds', 'brass', 'percussion', 'keys', 'high_strings', 'low_strings'],
            'meters': ['4/4','3/4','2/4','6/8','2/2','3/8','9/8','12/8','6/4','5/4','3/2','1/4','7/8','5/8','4/2']}
    OUTPUT.write_text('// Generated by training/scripts/export_joint_arranger_js.py.\n'
                      '// Six-group classifier from curated MIDI; it does not generate new notes.\n'
                      f'export const ARRANGER_META = {json.dumps(meta, ensure_ascii=False, separators=(",", ":"))};\n'
                      f'export const ARRANGER_MANIFEST = {json.dumps(manifest, separators=(",", ":"))};\n'
                      f'export const ARRANGER_WEIGHTS_BASE64 = "{base64.b64encode(np.concatenate(parts).tobytes()).decode()}";\n')
    torch.manual_seed(929)
    cases = []
    for signature, meter, bar_len, notes in [
        ('4/4', 0, 48, [(60,0,12),(48,0,24),(67,12,12),(72,24,6)]),
        ('6/8', 3, 36, [(64,0,18),(52,0,18),(71,12,8),(76,24,12),(44,30,6)])
    ]:
        n = len(notes)
        row = {name: torch.zeros(1,65,dtype=torch.long) for name in ('pitch','pos','dur')}
        row['pitch'][:] = PITCH_CLS + 1
        row['pitch'][0,0] = PITCH_CLS
        for i,(pitch,pos,dur) in enumerate(notes,1):
            row['pitch'][0,i] = pitch
            row['pos'][0,i] = pos
            row['dur'][0,i] = dur
        row['meter'] = torch.tensor([meter])
        row['bar_len'] = torch.tensor([bar_len])
        row['valid'] = torch.zeros(1,65,dtype=torch.bool)
        row['valid'][0,:n+1] = True
        with torch.no_grad():
            logits,presence = model(row)
        cases.append({'signature':signature,'meter':meter,'barLen':bar_len,
                      'notes':notes,'expected':logits[0,:n].tolist(),
                      'presence':presence[0].tolist()})
    FIXTURE.write_text(json.dumps({'cases':cases}))
    print(json.dumps({'floats':offset,'checkpoint':meta['checkpointSha256'],'fixture':str(FIXTURE)}))


if __name__ == '__main__':
    main()
