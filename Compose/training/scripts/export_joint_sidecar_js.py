#!/usr/bin/env python3
"""Export the selected expression sidecar and a small PyTorch parity probe.

The continued R/H/B/M backbone is exported separately by export_joint_js.py.
This file exports only non-base tensors; it cannot silently replace that backbone.
"""
import base64
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
from train_joint_expression import ExpressionSidecar, FIELDS
from joint_model import StructuredJoint

ROOT = Path(__file__).resolve().parents[2]
CHECKPOINT = ROOT / 'training/runs/joint-continued-expression-v1/best.pt'
BASE = ROOT / 'training/runs/joint-continued-expression-v1/best-base.pt'
OUTPUT = ROOT / 'frontend/vendor/lib/joint-expression-weights.js'
FIXTURE = ROOT / 'tests/fixtures/joint-expression-parity.json'


def main():
    checkpoint = torch.load(CHECKPOINT, map_location='cpu', weights_only=False)
    base_hash = hashlib.sha256(BASE.read_bytes()).hexdigest()
    selected_base = torch.load(BASE, map_location='cpu', weights_only=False)
    if (checkpoint['step'] != selected_base['step'] or not checkpoint['fineTunedBase']
            or checkpoint['baseHash'] != selected_base['sourceHash']):
        raise ValueError('Expression checkpoint and selected fine-tuned backbone differ')
    state = checkpoint['sidecar']
    parts, manifest, offset = [], [], 0
    for name, tensor in state.items():
        if name.startswith('base.'):
            raise ValueError('Unexpected embedded backbone tensor')
        array = tensor.detach().cpu().numpy().astype('<f4').ravel()
        manifest.append([name, offset, list(tensor.shape)])
        parts.append(array)
        offset += array.size
    blob = np.concatenate(parts).tobytes()
    meta = {'checkpointSha256': hashlib.sha256(CHECKPOINT.read_bytes()).hexdigest(),
            'baseSha256': base_hash, 'step': checkpoint['step'], 'vocab': checkpoint['vocab'],
            'slots': [16, 4, 4], 'fields': FIELDS, 'float32Count': offset}
    OUTPUT.write_text('// Generated by training/scripts/export_joint_sidecar_js.py.\n'
                      '// Keep with the matching continued backbone; see vendor/JOINT-MODEL-NOTICE.txt.\n'
                      f'export const EXPRESSION_META = {json.dumps(meta, ensure_ascii=False, separators=(",", ":"))};\n'
                      f'export const EXPRESSION_MANIFEST = {json.dumps(manifest, separators=(",", ":"))};\n'
                      f'export const EXPRESSION_WEIGHTS_BASE64 = "{base64.b64encode(blob).decode()}";\n')
    torch.manual_seed(20929)
    model = ExpressionSidecar(StructuredJoint(), checkpoint['vocab'])
    model.load_state_dict(state, strict=False)
    model.eval()
    # A deterministic probe exercises every field embedding, the zero-event mask,
    # all three role count heads and all seven field heads.
    events = [[], [{'role': 0, 'pitch': 60, 'sub': 11, 'dur': 17,
                    'ratio': 12, 'dynamic': 6, 'accent': 1, 'wedge': 2},
                   {'role': 2, 'pitch': 67, 'sub': 1, 'dur': 31,
                    'ratio': 1, 'dynamic': 0, 'accent': 0, 'wedge': 0}]]
    h = torch.randn(3, 96)
    coarse_tokens = [4, 3, 28, 15]
    with torch.no_grad():
        f = torch.zeros(1, 2, 3, 16, 7, dtype=torch.long)
        count = torch.zeros(1, 2, 3, dtype=torch.long)
        for step, notes in enumerate(events):
            for note in notes:
                role = note['role']; slot = count[0, step, role]
                f[0, step, role, slot] = torch.tensor([note[key] for key in FIELDS])
                count[0, step, role] += 1
        x = model.role.weight[None, None, :, None, :]
        for j, key in enumerate(FIELDS):
            x = x + model.embed[key](f[..., j])
        mask = (torch.arange(16)[None, None, None, :] < count[..., None]).unsqueeze(-1)
        x = (x * mask).sum((2, 3)) / count.sum(-1).clamp(min=1).sqrt()[..., None]
        extra = model.input_norm(x) * (count.sum(-1) > 0)[..., None]
        base = selected_base['state_dict']
        model.base.load_state_dict(base)
        coarse = model.coarse(sum(torch.nn.functional.embedding(
            torch.tensor(token), base[f'tok.{i}.weight']) for i, token in enumerate(coarse_tokens)))
        outputs = []
        for r in range(3):
            source = h[r] + coarse
            counts = model.count_head[r](source)
            slot_source = model.out_norm(source + model.slot(torch.tensor(0)))
            fields = {key: model.field_head[key](slot_source) for key in FIELDS}
            outputs.append({'counts': counts.tolist(), 'fields': {k: v.tolist() for k, v in fields.items()}})
        validation = json.loads((ROOT / 'tests/fixtures/joint-continued-parity.json').read_text())['cases'][0]
        I = validation['inputs']; length = 128
        row = {}
        for key in ('R','H','B','M','pos','meter','level','phrase','lkey','beatphase','barlen','beatlen'):
            values = I[key][:length]
            values += [values[-1]] * (length-len(values))
            row[key] = torch.tensor([values],dtype=torch.long)
        for key in ('domain','style','refmode'):
            row[key] = torch.tensor([validation['globals'][key]],dtype=torch.long)
        chord=[];since=[];change=[];cur=0;run=0
        for token in row['H'][0].tolist():
            if token>=3:
                cur=token-3;run=0
            else:
                run+=1
            chord.append(cur);since.append(min(run,17));change.append(int(token>=3))
        for key,values in (('chord',chord),('since',since),('change',change)):
            row[key]=torch.tensor([values],dtype=torch.long)
        added=torch.zeros(1,length,96)
        added[0,0]=extra[0,1]
        lg,feature=model.base(row,extra_step=added,return_features=True)
        backbone_probe={'source':validation['source'],'extra':extra[0,1].tolist(),
                        'logits':{name:lg[name][0,0].tolist() for name in ('R','H','B','M')},
                        'hidden':feature[0,0].tolist()}
    FIXTURE.write_text(json.dumps({'events': events, 'hidden': h.tolist(),
                                   'coarseTokens': coarse_tokens, 'extra': extra[0].tolist(),
                                   'outputs': outputs, 'backboneProbe':backbone_probe}))
    print(json.dumps({'floats': offset, 'baseSha256': base_hash, 'fixture': str(FIXTURE)}))


if __name__ == '__main__':
    main()
